import esbuild from 'esbuild';
import builtins from 'builtin-modules';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

/**
 * Build the standalone convert-all CLI.
 *
 * Bundles the plugin's converter pipeline (mineruConverter, epubParser,
 * pdfRenderer, bibtexConverter, layout, helpers, bib/helpers) into a single
 * self-contained Node script, mapping `obsidian` to the local shim. Also
 * copies pdf.js's worker next to the bundle so getPdfPageCount works.
 *
 * Output: vault/scripts/convert-all/convert-all.cjs
 */
const here = path.dirname(fileURLToPath(import.meta.url));
const outfile = process.env.CONVERT_ALL_OUT || 'convert-all.cjs';
const outdir = path.dirname(outfile);

const obsidianShim = new URL('./obsidian-shim.ts', import.meta.url).pathname;

const obsidianResolvePlugin = {
  name: 'obsidian-shim',
  setup(build) {
    build.onResolve({ filter: /^obsidian$/ }, (args) => {
      return { path: obsidianShim, namespace: 'file' };
    });
  },
};

async function build() {
  await esbuild.build({
    entryPoints: ['./scripts/convert-all-cli.ts'],
    bundle: true,
    platform: 'node',
    target: 'node18',
    format: 'cjs',
    outfile,
    logLevel: 'info',
    sourcemap: false,
    minify: false,
    treeShaking: true,
    banner: {
      js: '#!/usr/bin/env node\n/* Generated by scripts/build-convert-all.mjs */',
    },
    plugins: [obsidianResolvePlugin],
    external: [...builtins, 'node:*', 'electron'],
  });

  // Ship pdf.js worker next to the bundle.
  const workerSrc = path.join(here, '..', 'node_modules', 'pdfjs-dist', 'legacy', 'build', 'pdf.worker.min.js');
  if (fs.existsSync(workerSrc)) {
    fs.mkdirSync(outdir, { recursive: true });
    fs.copyFileSync(workerSrc, path.join(outdir, 'pdf.worker.min.js'));
    console.log(`Copied pdf.worker.min.js -> ${path.join(outdir, 'pdf.worker.min.js')}`);
  } else {
    console.warn('pdf.js worker not found; pdf page counts may fail in the CLI.');
  }
}

build().catch(() => process.exit(1));
